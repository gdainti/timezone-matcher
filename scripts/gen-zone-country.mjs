// Builds src/lib/zone-country.ts: IANA zone (and its legacy aliases) -> ISO country code.
// Source: the system tz database (zone.tab + link lines in tzdata.zi).
// Run: node scripts/gen-zone-country.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs'

const dir = process.argv[2] ?? '/usr/share/zoneinfo'
const map = {}
for (const line of readFileSync(`${dir}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [cc, , tz] = line.split('\t')
  map[tz] = cc
}
for (const line of readFileSync(`${dir}/tzdata.zi`, 'utf8').split('\n')) {
  if (!line.startsWith('L ')) continue
  const [, target, alias] = line.split(' ')
  if (map[target] && !map[alias]) map[alias] = map[target]
}
const entries = Object.keys(map)
  .sort()
  .map((tz) => `  '${tz}': '${map[tz]}',`)
writeFileSync(
  'src/lib/zone-country.ts',
  `// Generated by scripts/gen-zone-country.mjs from the tz database. Do not edit.\nexport const ZONE_COUNTRY: Record<string, string> = {\n${entries.join('\n')}\n}\n`,
)
console.log(entries.length, 'zones')
